interface LanguageContextValue {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => Promise<void>;
  t: (text: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

async function loadLanguage(): Promise<AppLanguage> {
  const saved =
    Platform.OS === "web"
      ? window.localStorage.getItem("poultech-language")
      : await SecureStore.getItemAsync("poultech-language");
  return saved === "hi" || saved === "mr" ? saved : "en";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>("en");

  useEffect(() => {
    void loadLanguage()
      .then(setLanguageState)
      .catch((error: unknown) => {
        console.error("Could not load the saved language preference.", error);
      });
  }, []);

  const setLanguage = async (nextLanguage: AppLanguage) => {
    if (Platform.OS === "web") {
      window.localStorage.setItem("poultech-language", nextLanguage);
    } else {
      await SecureStore.setItemAsync("poultech-language", nextLanguage);
    }
    setLanguageState(nextLanguage);
  };

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t: (text: string) => translations[language][text] ?? text,
    }),
    [language],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider.");
  return context;
}
