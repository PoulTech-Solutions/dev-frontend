const LOCAL_DIGITS = "०१२३४५६७८९";

export function localizeDigits(value: number | string, language: AppLanguage) {
  const text = String(value);
  if (language === "en") return text;
  return text.replace(/[0-9]/g, (digit) => LOCAL_DIGITS[Number(digit)] ?? digit);
}

interface LanguageContextValue {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => Promise<void>;
  t: (text: string) => string;
  n: (value: number | string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

async function loadLanguage(): Promise<AppLanguage> {
  const saved =
    Platform.OS === "web"
      ? window.localStorage.getItem("poultech-language")
      : await SecureStore.getItemAsync("poultech-language");
  return saved === "hi" || saved === "mr" ? saved : "en";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>("en");

  useEffect(() => {
    void loadLanguage()
      .then(setLanguageState)
      .catch((error: unknown) => {
        console.error("Could not load the saved language preference.", error);
      });
  }, []);

  const setLanguage = async (nextLanguage: AppLanguage) => {
    if (Platform.OS === "web") {
      window.localStorage.setItem("poultech-language", nextLanguage);
    } else {
      await SecureStore.setItemAsync("poultech-language", nextLanguage);
    }
    setLanguageState(nextLanguage);
  };

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t: (text: string) => {
        const dict = translations[language];
        if (!text) return text;
        if (dict[text]) return dict[text];
        // Composed UI copy like "layer · Pune · Layer record book"
        if (text.includes(" · ")) {
          return text
            .split(" · ")
            .map((part) => dict[part] ?? part)
            .join(" · ");
        }
        return text;
      },
      n: (value: number | string) => localizeDigits(value, language),
    }),
    [language],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider.");
  return context;
}
